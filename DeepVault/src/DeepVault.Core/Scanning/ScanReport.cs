using System.Net;
using System.Text;
using DeepVault.Core.Catalog;
using DeepVault.Core.Engines;
using DeepVault.Core.IO;
using DeepVault.Core.Util;

namespace DeepVault.Core.Scanning;

/// <summary>Self-contained HTML report of a scan: source, partitions, methods, results by state/type/engine, gaps and messages.</summary>
public static class ScanReport
{
    public static string BuildHtml(ProjectDatabase db)
    {
        string E(string? s) => WebUtility.HtmlEncode(s ?? "");
        var src = db.GetMetaJson<SourceIdentity>("source");
        var sum = db.GetMetaJson<ScanSummary>("scan_summary");
        var opt = db.GetMetaJson<ScanOptions>("scan_options");
        var sb = new StringBuilder();
        sb.Append("<!doctype html><html><head><meta charset=\"utf-8\"><title>DeepVault scan report</title><style>body{font-family:Segoe UI,Arial,sans-serif;margin:24px;color:#1b1f24}")
          .Append("table{border-collapse:collapse;margin:8px 0 18px}td,th{border:1px solid #d0d7de;padding:4px 8px;text-align:left;font-size:13px}th{background:#f3f4f6}.warn{background:#fff8c5;border:1px solid #d4a72c;padding:8px 12px}</style></head><body>");
        sb.Append("<h1>DeepVault scan report</h1>");
        sb.Append($"<p><b>Source:</b> {E(src?.Describe())} ({E(src?.Kind)})<br><b>Mode:</b> {E(db.GetMeta("mode"))}<br><b>Started:</b> {E(db.GetMeta("scan_started"))}<br><b>Finished:</b> {E(db.GetMeta("scan_finished"))}<br>");
        sb.Append($"<b>Outcome:</b> {E(db.GetMeta("scan_status"))}{(sum != null ? $" in {sum.Duration:hh\\:mm\\:ss}" : "")}<br><b>Methods:</b> {E(opt?.Methods.ToString())}; scope {E(opt?.Scope.ToString())}</p>");
        if (sum != null && !sum.IsExhaustive)
            sb.Append("<p class=\"warn\">This scan is <b>not exhaustive</b>: it was stopped, or some areas could not be read. See the regions below.</p>");
        if (sum != null)
            sb.Append($"<p>Deep-scan plan: {Bytes.FormatSize(sum.BytesPlannedRaw)}; excluded by scope (space used by existing files): {Bytes.FormatSize(sum.BytesExcludedByScope)}; unreadable sectors: {sum.BadSectors:N0}; carved results merged with named results: {sum.Correlated:N0}.</p>");
        sb.Append("<h2>Partitions and volumes</h2><table><tr><th>#</th><th>Status</th><th>File system</th><th>Offset</th><th>Size</th><th>Type</th><th>Evidence</th></tr>");
        foreach (var p in db.LoadPartitions())
            sb.Append($"<tr><td>{p.Index}</td><td>{E(p.Status)}</td><td>{E(p.FileSystem)}</td><td>{p.Offset:N0}</td><td>{Bytes.FormatSize(p.Length)}</td><td>{E(p.Type)} {E(p.Name)}</td><td>{E(p.Evidence)}</td></tr>");
        sb.Append("</table><h2>Results by state</h2><table><tr><th>View</th><th>Candidates</th></tr>");
        foreach (ResultView v in Enum.GetValues<ResultView>()) sb.Append($"<tr><td>{v}</td><td>{db.CountView(v):N0}</td></tr>");
        sb.Append("</table><h2>Results by category</h2><table><tr><th>Category</th><th>Candidates</th></tr>");
        foreach (var (k, n) in db.CountsBy("category").OrderByDescending(x => x.Value))
            sb.Append($"<tr><td>{E(int.TryParse(k, out var c) ? FileTypes.CategoryName((FileCategory)c) : k)}</td><td>{n:N0}</td></tr>");
        sb.Append("</table><h2>Results by recovery method</h2><table><tr><th>Methods</th><th>Candidates</th></tr>");
        foreach (var (k, n) in db.CountsBy("engines").OrderByDescending(x => x.Value))
            sb.Append($"<tr><td>{E(int.TryParse(k, out var e) ? ((EngineId)e).ToString() : k)}</td><td>{n:N0}</td></tr>");
        sb.Append("</table><h2>Unread or partially read regions</h2><table><tr><th>Kind</th><th>Offset</th><th>Length</th><th>Note</th></tr>");
        var regions = db.GetRegions();
        if (regions.Count == 0) sb.Append("<tr><td colspan=4>None</td></tr>");
        foreach (var r in regions) sb.Append($"<tr><td>{r.Kind}</td><td>{r.Offset:N0}</td><td>{Bytes.FormatSize(r.Length)}</td><td>{E(r.Note)}</td></tr>");
        sb.Append("</table><h2>Engine messages</h2><table><tr><th>Time (UTC)</th><th>Severity</th><th>Message</th></tr>");
        foreach (var (t, i) in db.GetIssues()) sb.Append($"<tr><td>{t:u}</td><td>{i.Severity}</td><td>{E(i.Message)}</td></tr>");
        sb.Append("</table><p>Generated by DeepVault. The report lists file names found on the scanned drive; it contains no file contents.</p></body></html>");
        return sb.ToString();
    }

    public static void Write(ProjectDatabase db, string path)
    {
        using var fs = new FileStream(path, FileMode.CreateNew, FileAccess.Write);
        using var w = new StreamWriter(fs, new UTF8Encoding(false));
        w.Write(BuildHtml(db));
    }
}
